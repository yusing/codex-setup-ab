import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { ensureDependencyImage } from "./dependencies";
import { runLaunch } from "./launch";
import { checked } from "./process";
import { executeSemanticCheck, type SemanticCheck } from "./semantic";
import { qualifySemanticCheck } from "./semantic-qualification";
import { readState } from "./state";

const task = "mekugi-source-tools";
const source = process.env.CODEX_AB_MEKUGI_SOURCE;
const live = process.env.CODEX_AB_LIVE_DOCKER === "1" && source ? test : test.skip;

const generatedHeader = "// Code generated by protoc; DO NOT EDIT.\n";
const wideInput = ("x".repeat(32767) + "é").repeat(3);
const observations = {
  "mcat-read": {
    raw: [0, "α\r\nbeta\rgamma\nlast", false],
    large: [0, new Bun.CryptoHasher("sha256").update(wideInput).digest("hex"), false],
    generated: [0, generatedHeader + "package gen\n", false],
    generated_range: [0, generatedHeader, true],
  },
  "outline-recovery": {
    flow: [0, true, ["é", "abc", "next", "Title"]],
    import: [0, true, ["\uD800"]],
    strict: [0, true, ["", "/\uD800", "/normal"]],
    recovery: [0, false, ["", "/\uD800", "/broken"]],
    go: [0, true, ["fmt", "os"]],
    bad_go: [0, false, true],
  },
  "cli-errors": { mcat: [1, 1, true], mfinspect: [1, 1, true] },
};

live("monorepo task qualifies retained behavior and every control offline", async () => {
  const root = await mkdtemp(join(process.env.CODEX_AB_LIVE_OUTPUT ?? tmpdir(), "mekugi-source-qualification-"));
  const docker = process.env.CODEX_AB_DOCKER_BIN ?? "docker";
  const gitKeys = ["GIT_CONFIG_NOSYSTEM", "GIT_CONFIG_GLOBAL"] as const;
  const previousGitSettings = gitKeys.map(key => [key, process.env[key]] as const);
  process.env.GIT_CONFIG_NOSYSTEM = "1";
  process.env.GIT_CONFIG_GLOBAL = "/dev/null";
  try {
    const runDir = await runLaunch({ task, source: source!, "prepare-only": true, "output-parent": root });
    const state = await readState(runDir);
    state.timeout_seconds = 180;
    await ensureDependencyImage(docker, runDir, state, AbortSignal.timeout(20 * 60 * 1000));
    const contract = state.criteria!.contract;
    const existing = contract.existing_test_verification!;
    const probe = existing.cases[0]!;
    if (probe.kind !== "command") throw new Error("Expected retained CLI observation");

    const baseline = resolve(runDir, state.arms.stock.repository);
    const reference = join(root, "reference");
    await checked(["git", "clone", "--no-hardlinks", baseline, reference]);
    const patch = state.upstream_reference!.files.find(file => file.path.endsWith("/changes.patch"))!;
    await checked(["git", "-C", reference, "apply", "--binary", resolve(runDir, patch.path)]);
    const command = probe.command;
    const checks: SemanticCheck = {
      criterion: "existing-tests", command, files: [], verification: existing,
      rationale: "Observe retained source ranges, invalid input, and ordinary outlines.",
    };
    for (const [label, candidate] of [["baseline", baseline], ["reference", reference]]) {
      const evidence = await executeSemanticCheck({
        runDir, state, candidate, output: join(root, label + "-retained"),
        name: `codex-ab-mekugi-retained-${crypto.randomUUID()}`, check: checks, docker,
      });
      expect(evidence.execution?.verifier?.status, JSON.stringify(evidence.execution)).toBe("passed");
    }
    expect(contract.criteria.map(({ id }) => id)).toEqual(Object.keys(observations));
    const results = await Promise.allSettled(Object.entries(observations).map(async ([criterion, expected]) => {
      const check: SemanticCheck = {
        criterion, command, files: [], rationale: "Observe the native CLI through its entry point.",
        verification: { ...existing, cases: [{ ...probe, id: criterion, args: [criterion], expected: JSON.stringify(expected) }] },
      };
      const result = await qualifySemanticCheck({
        runDir, output: join(root, criterion), state, check, controls: contract.evaluator_controls,
        docker, evaluatorModel: "frozen-task-fixture",
      });
      expect(result.status, JSON.stringify(result.results.map(({ control, evidence }) =>
        [control, evidence.execution?.verifier ?? evidence.execution?.stderr]))).toBe("qualified");
      for (const { expected, evidence } of result.results) {
        expect(evidence.execution?.verifier?.status).toBe(expected === "pass" ? "passed" : "assertion_failure");
      }
    }));
    for (const result of results) if (result.status === "rejected") throw result.reason;
  } finally {
    for (const [key, value] of previousGitSettings) {
      if (value === undefined) delete process.env[key];
      else process.env[key] = value;
    }
    await rm(root, { recursive: true, force: true });
  }
}, 30 * 60 * 1000);
